		<h2>How does the application access Jira data (issues, projects, user information, etc)?</h2>

		<p>
			Advanced Story Maps and Story Maps for Jira are client-side applications which run in the users web browser.
			We do NOT access, copy or transfer any Jira data to our own infrastructure. All data manipulation is handled on
			the end-user machine with their own user credentials.
		</p>

		<h2>Which data does the application store and process?</h2>

		<p>
			In order to save application settings and personal preferences, the app uses Jira entity and app properties to store
			data in the Jira host instance. This is true for both Jira Cloud as well as Jira Data Center and Server.
		</p>

		<p>The following data is stored by the application in the Jira instance:</p>
		<ul>
			<li>A list of story maps per project</li>
			<li>Configuration data for each story map (can contain board ids and field ids)</li>
			<li>User preferences attached to the user profile</li>
			<li>Global settings</li>
		</ul>

		<p>The following data is stored on our infrastructure:</p>
		<ul>
			<li>Licensing information and the client keys required for the application to work (legacy Connect and Data Center editions only)</li>
		</ul>

		<p>
			The Forge versions of Story Maps for Jira and Advanced Story Maps for Jira do not store any data
			on our infrastructure. Licensing and install information are handled entirely by Atlassian, and all
			application data lives in your Jira instance.
		</p>

		<h2>Do you collect and store personal identifying information (PII)?</h2>

		<p>
			The Forge versions of Story Maps for Jira and Advanced Story Maps for Jira do not collect or store
			any PII, and do not use third-party analytics or error-reporting services.
		</p>

		<h2>Which analytics software is used by the application?</h2>

		<p>
			The Forge versions of Story Maps for Jira and Advanced Story Maps for Jira do not use any analytics
			software. No usage data, personal data, or error reports are sent to us or to any third party.
		</p>

		<p>
			The legacy Connect and Data Center/Server editions can optionally send anonymized error reports via
			Sentry when analytics is enabled. We use Sentry to collect error reports generated by the application
			in case of a major failure. In this case an error report with an overview of all requests and their
			status is sent to us. We anonymize all Jira data when sending this report, and it stops working when
			you disable analytics in the app's global settings.
		</p>
